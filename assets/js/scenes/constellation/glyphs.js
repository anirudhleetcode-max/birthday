// for names that don't start with A–Z: a tiny heart
const HEART = [[[2, 0.2], [0.4, 2.4], [0, 4.2], [0.8, 5.6], [2, 5.2], [3.2, 5.6], [4, 4.2], [3.6, 2.4], [2, 0.2]]];

/** First letter of a name → { stars: [[x,y]…] (unique, 0..1 box, y up), segments: [[a, b]…] (star indices) }. */
export function glyphFor(name) {
  const ch = String(name || '').trim().normalize('NFD').replace(/[̀-ͯ]/g, '').charAt(0).toUpperCase();
  const strokes = GLYPHS[ch] || HEART;
  const stars = [];
  const key = (p) => `${p[0].toFixed(2)},${p[1].toFixed(2)}`;
  const index = new Map();
  const id = (p) => {
    const k = key(p);
    if (!index.has(k)) { index.set(k, stars.length); stars.push([p[0] / 4, p[1] / 6]); }
    return index.get(k);
  };
  const segments = [];
  for (const line of strokes) {
    for (let i = 0; i < line.length - 1; i++) segments.push([id(line[i]), id(line[i + 1])]);
  }
  return { letter: GLYPHS[ch] ? ch : '♥', stars, segments };
}
